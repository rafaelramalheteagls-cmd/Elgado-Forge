function makeProgTemplate(cfg: {
  id: string;
  title: string;
  weaponClass: WeaponClass;
  rankTier: RankTier;
  minMr: number;
  minAr: number;
  playstyle: string;
  summary: string;
  weaponId: string;
  helmId: string;
  chestId: string;
  armsId: string;
  waistId: string;
  legsId: string;
  talisman?: TalismanItem;
  rampageDecoId?: string;
  scrollMode?: 'Red' | 'Blue';
  decos?: Partial<BuildLoadout['decorations']>;
}): MetaBuildTemplate {
  return {
    id: cfg.id,
    title: cfg.title,
    weaponClass: cfg.weaponClass,
    rankTier: cfg.rankTier,
    minMr: cfg.minMr,
    minAr: cfg.minAr,
    playstyle: cfg.playstyle,
    summary: cfg.summary,
    loadout: {
      name: cfg.title,
      weaponClass: cfg.weaponClass,
      weaponId: cfg.weaponId,
      helmId: cfg.helmId,
      chestId: cfg.chestId,
      armsId: cfg.armsId,
      waistId: cfg.waistId,
      legsId: cfg.legsId,
      talisman:
        cfg.talisman ?? (cfg.rankTier === 'HR' ? HR_CHARM : DEFAULT_TALISMAN),
      rampageDecoId:
        cfg.rampageDecoId ??
        (cfg.rankTier === 'HR'
          ? ''
          : cfg.rankTier === 'Early MR'
          ? 'ramp_anti_wyvern'
          : 'ramp_anti_elder'),
      decorations: {
        weapon: cfg.decos?.weapon ?? [],
        helm: cfg.decos?.helm ?? [],
        chest: cfg.decos?.chest ?? [],
        arms: cfg.decos?.arms ?? [],
        waist: cfg.decos?.waist ?? [],
        legs: cfg.decos?.legs ?? [],
        talisman: cfg.decos?.talisman ?? [],
      },
      quriousWeapon: { ...EMPTY_Q_WEAPON },
      quriousArmor: { ...EMPTY_Q_ARMOR },
      scrollMode: cfg.scrollMode ?? 'Red',
    },
  };
}

